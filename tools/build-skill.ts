/**
 * Builds what the skill ships beside its sources, so that the skill folder is the whole package an
 * agent or a bot downloads, and needs nothing from this repository:
 *
 *   lib/bound-verify.mjs       the agent's verifier (src/verify.ts, with @bound/verifier and friends)
 *   bin/bound-verify.mjs       the command for bots in other languages (src/cli.ts and the example)
 *   reference/AGENT-API.md     the API reference, copied from AGENT-API.md
 *
 * Only @solana/kit stays external, since the agent installs it anyway (the skill's package.json).
 *
 *   node tools/build-skill.ts           write them
 *   node tools/build-skill.ts --check   fail if a committed file differs from a fresh build (CI)
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { rolldown } from 'rolldown';

const SKILL = 'skills/bound-protected-swap';

async function bundle(input: string, banner: string): Promise<string> {
  const b = await rolldown({
    input,
    external: id => id === '@solana/kit' || id.startsWith('@solana/kit/'),
    platform: 'node',
    logLevel: 'warn',
  });
  const { output } = await b.generate({ format: 'esm', banner });
  await b.close();
  return output[0].code;
}

// In order, each written before the next is built: the command bundles the example, which imports
// lib/bound-verify.mjs from disk, so the verifier must be current before the command is bundled.
const outputs: [path: string, make: () => Promise<string>][] = [
  [`${SKILL}/lib/bound-verify.mjs`, () => bundle(
    `${SKILL}/src/verify.ts`,
    '// Generated by tools/build-skill.ts from skills/bound-protected-swap/src/verify.ts and @bound/verifier. Do not edit.',
  )],
  [`${SKILL}/bin/bound-verify.mjs`, () => bundle(
    `${SKILL}/src/cli-entry.ts`,
    '#!/usr/bin/env node\n// Generated by tools/build-skill.ts from skills/bound-protected-swap/src/cli.ts and examples/swap.ts. Do not edit.',
  )],
  [`${SKILL}/reference/AGENT-API.md`, async () =>
    `<!-- Copied from AGENT-API.md by tools/build-skill.ts. Edit that file, not this one. -->\n\n${readFileSync('AGENT-API.md', 'utf8').replace(/\r\n/g, '\n')}`],
];

const lf = (s: string) => s.replace(/\r\n/g, '\n');
const check = process.argv.includes('--check');
let stale = 0;
for (const [path, make] of outputs) {
  const content = await make();
  if (check) {
    let committed = '';
    try {
      committed = readFileSync(path, 'utf8');
    } catch {
      // missing
    }
    if (lf(committed) !== lf(content)) {
      console.error(`${path} differs from a fresh build. Run: node tools/build-skill.ts`);
      stale++;
    } else console.log(`${path} matches its source`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`${path}: ${content.length} bytes`);
  }
}
if (stale) process.exit(1);
